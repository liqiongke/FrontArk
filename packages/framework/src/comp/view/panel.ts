/**
 * 数据区块（表单、表格等）的统一面板外观。
 *
 * 为什么用背景色而不是边框划界：
 * 横向排布的标签为了紧贴自己的控件采用右对齐，标签文字的左边缘因此长短不一。
 * 把整块表单放进一个统一底色的面板后，参差被收进面板内部，整块区域在视觉上聚合成
 * 一个整体，不再与页面中其它组件的左边界相互"较劲"；同时面板自身也不再需要边框。
 *
 * 表单与表格共用同一组类名，保证页面内所有数据区块的底色、圆角、内边距完全一致。
 */
export const PANEL = 'rounded-lg bg-surface text-surface-foreground';

/** 带统一内边距的面板：内边距数值与历史卡片保持一致，只保留一套 */
export const PANEL_PADDED = `${PANEL} p-4 sm:p-6`;
